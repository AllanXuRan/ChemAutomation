"""Add initial dynamics and calibrated-by-config virtual cameras to V12 scene.

Inputs:
    xarm_description/xarm5_lab_scene.xml (generated by build_lab_scene.py)
    physics_settings.json
Output:
    xarm_description/xarm5_lab_physics.xml (original untouched)

Requires Python standard library only; the next scripts require mujoco, numpy, PIL.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent
DEFAULT_INPUT = ROOT / "xarm_description" / "xarm5_lab_scene.xml"
DEFAULT_CONFIG = ROOT / "physics_settings.json"


def vector(values):
    return " ".join(f"{float(v):.10g}" for v in values)


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1],
            a[2] * b[0] - a[0] * b[2],
            a[0] * b[1] - a[1] * b[0])


def normal(a):
    d = math.sqrt(sum(x * x for x in a))
    if d < 1e-9:
        raise ValueError("Camera position and target must be different")
    return tuple(x / d for x in a)


def camera_axes(position, target):
    forward = normal(tuple(t - p for p, t in zip(position, target)))
    right = cross(forward, (0.0, 0.0, 1.0))
    if math.sqrt(sum(x*x for x in right)) < 1e-7:
        right = (1.0, 0.0, 0.0)
    else:
        right = normal(right)
    up = normal(cross(right, forward))
    return vector((*right, *up))


def get_world(root):
    world = root.find("worldbody")
    if world is None:
        raise RuntimeError("The input scene has no <worldbody> element")
    return world


def set_physics_option(root, config):
    option = root.find("option")
    if option is None:
        option = ET.Element("option")
        compiler = root.find("compiler")
        idx = list(root).index(compiler) + 1 if compiler is not None else 0
        root.insert(idx, option)
    option.set("timestep", str(float(config["timestep_s"])))
    option.set("gravity", "0 0 -9.81")
    option.set("integrator", "implicitfast")
    option.set("solver", "Newton")
    option.set("iterations", "70")


def add_dynamic_plate(world, config):
    plate = next((b for b in world.iter("body")
                  if b.get("name") == "reaction_plate"), None)
    if plate is None:
        raise RuntimeError("Could not find reaction_plate in V12 scene")
    if plate.find("freejoint") is None and not any(j.get("type") == "free" for j in plate.findall("joint")):
        plate.insert(0, ET.Element("freejoint", {"name": "reaction_plate_free"}))
    plate_geom = next((g for g in plate.findall("geom")
                       if g.get("name") == "reaction_plate_box"), None)
    if plate_geom is None:
        raise RuntimeError("Could not find reaction_plate_box")
    plate_geom.set("mass", str(float(config["plate_mass_kg"])))
    plate_geom.set("friction", vector(config["plate_friction"]))
    plate_geom.set("contype", "1")
    plate_geom.set("conaffinity", "1")
    # Start slightly above the support, so the first settling test produces contact.
    pose = [float(x) for x in plate.get("pos", "0 0 0").split()]
    if len(pose) != 3:
        raise RuntimeError("Reaction plate must have a 3D body position")
    # A tabletop source stack has neighbouring plates immediately above it.
    lift = 0.0 if world.find("body[@name='ot2_stack_plate_1_body']") is not None else float(config['plate_initial_lift_m'])
    pose[2] += lift
    plate.set("pos", vector(pose))
    return plate


def add_surface_physics(world, config):
    names = {
        "temperature_aluminium_block", "temperature_module_body",
        "versamax_sliding_tray", "ot2_base", "lab_table_top", "table_top"
    }
    count = 0
    for g in world.iter("geom"):
        if g.get("name") in names:
            g.set("friction", vector(config["support_friction"]))
            g.set("contype", "1")
            g.set("conaffinity", "1")
            count += 1
    return count


def set_robot_stabilization(root, config):
    robot = get_world(root).find("body[@name='lab_robot_mount']")
    bodies = 0
    if robot is not None:
        for b in robot.iter("body"):
            # A temporary simulation convenience, not a calibrated real controller.
            b.set("gravcomp", str(float(config["robot_gravcomp_fraction"])))
            bodies += 1
    changed = 0
    acts = root.find("actuator")
    if acts is not None:
        for act in acts:
            joint = act.get("joint", "")
            if act.tag == "position" and joint in {f"joint{i}" for i in range(1,6)}:
                act.set("kp", str(float(config["arm_position_kp"])))
                act.set("kv", str(float(config["arm_position_kv"])))
                changed += 1
    return bodies, changed


def add_cameras(world, camera_configs):
    targets = {s.get("name"): tuple(map(float, s.get("pos").split()))
               for s in world.findall("site") if s.get("name") and s.get("pos")}
    added = []
    for name, conf in camera_configs.items():
        site_name = conf["target_site"]
        if site_name not in targets:
            raise RuntimeError(f"Site {site_name!r} missing: available {list(targets)}")
        target = targets[site_name]
        offset = conf["offset_world_xyz_m"]
        if len(offset) != 3:
            raise ValueError(f"Camera {name}: offset must contain 3 numbers")
        pos = tuple(target[i] + float(offset[i]) for i in range(3))
        if any(c.get("name") == name for c in world.iter("camera")):
            raise ValueError(f"Camera name already exists: {name}")
        ET.SubElement(world, "camera", name=name, pos=vector(pos),
                      xyaxes=camera_axes(pos, target), fovy=str(float(conf["fovy_deg"])))
        added.append((name, pos, site_name))
    return added


def build(scene_path, config_path, output_path):
    if not scene_path.is_file():
        raise FileNotFoundError(f"First generate V12 scene: {scene_path}")
    config = json.loads(config_path.read_text(encoding="utf-8"))
    root = ET.parse(scene_path).getroot()
    world = get_world(root)
    set_physics_option(root, config["physics"])
    add_dynamic_plate(world, config["physics"])
    surfaces = add_surface_physics(world, config["physics"])
    bodies, acts = set_robot_stabilization(root, config["physics"])
    added = add_cameras(world, config["cameras"])
    ET.indent(root, space="  ")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    ET.ElementTree(root).write(output_path, encoding="utf-8", xml_declaration=True)
    # XML parsing only: full MuJoCo compilation requires original URDF meshes locally.
    ET.parse(output_path)
    print(f"Output: {output_path}")
    print(f"Dynamic plate: enabled; surface friction geoms: {surfaces}")
    print(f"Robot stabilization bodies: {bodies}; position actuators tuned: {acts}")
    for name, pos, target in added:
        print(f"Camera {name}: world_pos={tuple(round(x, 3) for x in pos)} -> {target}")
    print("NOTE: Tabletop input plates have free joints; legacy fixed stack plates are made dynamic by physics_runtime.")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--scene", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--output", type=Path, default=None)
    args = parser.parse_args()
    input_path = args.scene.resolve()
    output_path = args.output.resolve() if args.output else input_path.with_name("xarm5_lab_physics.xml")
    if output_path == input_path:
        raise SystemExit("Refusing to overwrite your original layout scene")
    build(input_path, args.config.resolve(), output_path)


if __name__ == "__main__":
    main()
